"""Explicit non-secret runtime settings permitted in shareable evidence."""

# Never collect by prefix: DLLM_* also contains authentication credentials,
# client policy secrets and private filesystem paths. New settings require an
# explicit decision before they become report metadata.
REPORT_KEYS = frozenset('''
DLLM_DEVICE DLLM_KERNELS DLLM_QUANTIZATION
DLLM_EXPERIMENTAL_HYBRID_OFFLOAD DLLM_EXPERIMENTAL_HYBRID_PIPELINE
DLLM_EXPERIMENTAL_HYBRID_Q4 DLLM_EXPERIMENTAL_LAYER_SPLIT
DLLM_EXPERIMENTAL_VISION DLLM_EXPERIMENTAL_XPU
DLLM_GEMMA_WEIGHT_DTYPE DLLM_GPT_OSS_ATTENTION DLLM_GPT_OSS_PREFILL
DLLM_HYBRID_METAL_SCAN DLLM_HYBRID_PIPELINE_BUDGETS_MIB
DLLM_HYBRID_PRECISION DLLM_HYBRID_PREFILL
DLLM_KQUANT_DENSE_CACHE_MIB DLLM_KQUANT_PREFILL_F32 DLLM_KV_CACHE_TOKENS
DLLM_LLAMA_PRECISION DLLM_LOGPROBS_KERNELS
DLLM_MAMBA2_COMPENSATED DLLM_MAMBA2_SSD DLLM_MAMBA_FUSED_DT
DLLM_METAL_WEIGHT_DTYPE DLLM_PARTITION_PACKED_PREFILL DLLM_PARTITION_REBIND
DLLM_PREFILL_GRAPHS DLLM_PREFILL_GRAPH_MAX_TOKENS
DLLM_Q4_STAGE_ADJACENT DLLM_Q4_STAGE_RUNTIME_ROPE DLLM_Q4_STAGE_RUNTIME_ROWS
DLLM_QWEN3_PRECISION DLLM_ROCM_MEMORY_GIB DLLM_SPECULATIVE_TOKENS
DLLM_T5_PREFILL_GRAPHS
'''.split())


def report_environment(environment):
    """Copy approved settings without exposing or modifying the source mapping."""
    return {name: environment[name] for name in sorted(REPORT_KEYS) if name in environment}
